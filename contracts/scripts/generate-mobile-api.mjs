import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const contractsDirectory = resolve(scriptDirectory, '..');
const repositoryDirectory = resolve(contractsDirectory, '..');
const openapiPath = resolve(contractsDirectory, 'openapi/v1.yaml');
const schemaPath = resolve(
  contractsDirectory,
  'schemas/v1/mobile-api.schema.json',
);
const outputDirectory = resolve(
  repositoryDirectory,
  'mobile/src/generated/api',
);
const banner =
  '// Generated by contracts/scripts/generate-mobile-api.mjs. Do not edit.\n\n';

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
const openapi = await openapiTS(pathToFileURL(openapiPath));

await mkdir(outputDirectory, { recursive: true });
await writeFile(
  resolve(outputDirectory, 'openapi.ts'),
  banner + astToString(openapi),
);
await writeFile(
  resolve(outputDirectory, 'schema.ts'),
  `${banner}export const mobileApiSchema = ${JSON.stringify(schema, null, 2)} as const;\n`,
);
await writeFile(
  resolve(outputDirectory, 'client.ts'),
  `${banner}import createClient from 'openapi-fetch';\nimport type { paths } from './openapi';\n\nexport function createMobileApiClient(baseUrl: string) {\n  return createClient<paths>({\n    baseUrl: baseUrl.replace(/\\/$/, ''),\n  });\n}\n`,
);
await writeFile(
  resolve(outputDirectory, 'index.ts'),
  `${banner}export { createMobileApiClient } from './client';\nexport { mobileApiSchema } from './schema';\nexport type { paths, operations, components } from './openapi';\n`,
);
